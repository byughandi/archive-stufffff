// Turns public/art/*.svg into src/lib/art.generated.ts so the art can be inlined and follow light/dark.
// #000000 -> var(--ink), #FFFFFF -> var(--paper), #D8232A -> var(--selvedge), #EDEDED -> var(--label).
// Filter and pattern ids get a placeholder that Art.svelte makes unique per instance.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../public/art/', import.meta.url);
const out = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  let s = readFileSync(new URL(f, dir), 'utf8').trim();
  s = s
    .replace(/#000000/gi, 'var(--ink)')
    .replace(/#FFFFFF/gi, 'var(--paper)')
    .replace(/#D8232A/gi, 'var(--selvedge)')
    .replace(/#EDEDED/gi, 'var(--label)')
    .replace(/id="(ink|hz)"/g, 'id="$1-__ID__"')
    .replace(/url\(#(ink|hz)\)/g, 'url(#$1-__ID__)')
    .replace(/^<svg([^>]*?) width="[\d.]+" height="[\d.]+"/, '<svg$1');
  out[f.replace(/\.svg$/, '')] = s;
}
writeFileSync(
  new URL('../src/lib/art.generated.ts', import.meta.url),
  '// Generated by scripts/build-art.mjs from public/art/*.svg. Do not edit.\nexport const ART: Record<string, string> = ' +
    JSON.stringify(out, null, 1) + ';\n'
);
console.log('art:', Object.keys(out).length, 'files');
